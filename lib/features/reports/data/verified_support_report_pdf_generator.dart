final class VerifiedSupportReportPdf {
  VerifiedSupportReportPdf({
    required this.kind,
    required this.fileName,
    required this.sourceFingerprint,
    required this.templateVersion,
    required this.sha256,
    required List<int> bytes,
  }) : bytes = List<int>.unmodifiable(bytes);

  final SupportReportArtifactKind kind;
  final String fileName;
  final String sourceFingerprint;
  final int templateVersion;
  final String sha256;
  final List<int> bytes;

  int get sizeBytes => bytes.length;
}

final class SupportReportPdfVerificationResult {
  const SupportReportPdfVerificationResult.valid()
    : isValid = true,
      reason = null;

  const SupportReportPdfVerificationResult.invalid(this.reason)
    : isValid = false;

  final bool isValid;
  final String? reason;
}

final class SupportReportPdfVerifier {
  const SupportReportPdfVerifier();

  SupportReportPdfVerificationResult verifyStructure(List<int> bytes) {
    try {
      if (bytes.length < 16) {
        return const SupportReportPdfVerificationResult.invalid(
          'Generated PDF is unexpectedly small.',
        );
      }

      final header = ascii.decode(bytes.sublist(0, 5), allowInvalid: true);

      if (header != '%PDF-') {
        return const SupportReportPdfVerificationResult.invalid(
          'Generated bytes do not expose a PDF header.',
        );
      }

      final tailStart = bytes.length > 1024 ? bytes.length - 1024 : 0;
      final tail = ascii.decode(bytes.sublist(tailStart), allowInvalid: true);

      if (!tail.contains('%%EOF')) {
        return const SupportReportPdfVerificationResult.invalid(
          'Generated PDF does not expose an EOF marker.',
        );
      }

      return const SupportReportPdfVerificationResult.valid();
    } catch (error) {
      return SupportReportPdfVerificationResult.invalid(
        'Generated PDF structural verification failed: $error',
      );
    }
  }
}

final class SupportReportPdfFontBytes {
  SupportReportPdfFontBytes({
    required Uint8List regular,
    required Uint8List bold,
  }) : regular = Uint8List.fromList(regular),
       bold = Uint8List.fromList(bold);

  final Uint8List regular;
  final Uint8List bold;
}

abstract interface class SupportReportPdfFontLoader {
  Future<SupportReportPdfFontBytes> load();
}

final class AssetBundleSupportReportPdfFontLoader
    implements SupportReportPdfFontLoader {
  const AssetBundleSupportReportPdfFontLoader();

  static const String regularAsset =
      'assets/p0_spikes/p0_05/fonts/Amiri-Regular.ttf';
  static const String boldAsset = 'assets/p0_spikes/p0_05/fonts/Amiri-Bold.ttf';

  @override
  Future<SupportReportPdfFontBytes> load() async {
    final regularData = await rootBundle.load(regularAsset);
    final boldData = await rootBundle.load(boldAsset);

    final regular = regularData.buffer.asUint8List(
      regularData.offsetInBytes,
      regularData.lengthInBytes,
    );
    final bold = boldData.buffer.asUint8List(
      boldData.offsetInBytes,
      boldData.lengthInBytes,
    );

    if (regular.isEmpty || bold.isEmpty) {
      throw StateError('Arabic PDF font assets are empty.');
    }

    return SupportReportPdfFontBytes(regular: regular, bold: bold);
  }
}

