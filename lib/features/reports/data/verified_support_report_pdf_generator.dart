final class SupportReportPdfDocumentModel {
  SupportReportPdfDocumentModel({
    required this.kind,
    required this.title,
    required this.sourceFingerprint,
    required this.templateVersion,
    required Iterable<SupportReportPdfField> metadata,
    required Iterable<SupportReportPdfStudentSection> students,
  }) : metadata = List<SupportReportPdfField>.unmodifiable(metadata),
       students = List<SupportReportPdfStudentSection>.unmodifiable(students);

  final SupportReportArtifactKind kind;
  final String title;
  final String sourceFingerprint;
  final int templateVersion;
  final List<SupportReportPdfField> metadata;
  final List<SupportReportPdfStudentSection> students;
}

final class SupportReportPdfContentMapper {
  const SupportReportPdfContentMapper();

  SupportReportPdfDocumentModel buildWeekly(
    ApprovedWeeklySupportReportSnapshot snapshot,
  ) {
    final context = snapshot.header.reportContext;
    final days = [...snapshot.days]
      ..sort((left, right) => left.localDate.compareTo(right.localDate));
    final students = [...snapshot.students]
      ..sort((left, right) => left.displayOrder.compareTo(right.displayOrder));

    return SupportReportPdfDocumentModel(
      kind: SupportReportArtifactKind.weekly,
      title: context == SupportReportContext.general
          ? 'تقرير قرآني الأسبوعي'
          : 'تقرير الجهة الأسبوعي',
      sourceFingerprint: snapshot.sourceFingerprint,
      templateVersion: snapshot.header.templateVersion,
      metadata: _metadata(
        header: snapshot.header,
        periodText:
            '${_dateText(snapshot.period.weekStart)} إلى '
            '${_dateText(snapshot.period.weekEnd)}',
        kindText: 'أسبوعي',
        sourceFingerprint: snapshot.sourceFingerprint,
      ),
      students: students.map(
        (student) => SupportReportPdfStudentSection(
          studentName: student.studentName,
          fields: _weeklyStudentFields(student, context),
          aggregates: const <SupportReportPdfField>[],
          dayLines: days.map(
            (day) => _weeklyDayLine(day, student.sourceStudentId),
          ),
        ),
      ),
    );
  }

  SupportReportPdfDocumentModel buildMonthly(
    ApprovedMonthlySupportReportSnapshot snapshot,
  ) {
    final context = snapshot.header.reportContext;
    final days = [...snapshot.days]
      ..sort((left, right) => left.localDate.compareTo(right.localDate));
    final students = [...snapshot.students]
      ..sort((left, right) => left.displayOrder.compareTo(right.displayOrder));

    return SupportReportPdfDocumentModel(
      kind: SupportReportArtifactKind.monthly,
      title: context == SupportReportContext.general
          ? 'تقرير قرآني الشهري'
          : 'تقرير الجهة الشهري',
      sourceFingerprint: snapshot.sourceFingerprint,
      templateVersion: snapshot.header.templateVersion,
      metadata: _metadata(
        header: snapshot.header,
        periodText:
            '${_dateText(snapshot.period.monthStart)} إلى '
            '${_dateText(snapshot.period.monthEnd)}',
        kindText: 'شهري',
        sourceFingerprint: snapshot.sourceFingerprint,
      ),
      students: students.map(
        (student) => SupportReportPdfStudentSection(
          studentName: student.studentName,
          fields: _monthlyStudentFields(student, context),
          aggregates: _monthlyAggregates(student, context),
          dayLines: days.map(
            (day) => _monthlyDayLine(day, student.sourceStudentId),
          ),
        ),
      ),
    );
  }

  List<SupportReportPdfField> _metadata({
    required SupportReportHeaderSnapshot header,
    required String periodText,
    required String kindText,
    required String sourceFingerprint,
  }) {
    final organizationLabel =
        header.reportContext == SupportReportContext.general
        ? 'المركز/المسجد'
        : 'الجهة';

    return <SupportReportPdfField>[
      SupportReportPdfField('المعلم', header.teacherName),
      SupportReportPdfField('الحلقة', header.halaqahName),
      SupportReportPdfField(organizationLabel, header.organizationName),
      SupportReportPdfField('الفترة', periodText),
      SupportReportPdfField('نسخة السياسة', header.policyVersion.toString()),
      SupportReportPdfField('نسخة القالب', header.templateVersion.toString()),
      SupportReportPdfField('بصمة المصدر', sourceFingerprint),
      SupportReportPdfField('نوع التقرير', kindText),
    ];
  }

  List<SupportReportPdfField> _weeklyStudentFields(
    ApprovedWeeklySupportReportStudentSnapshot student,
    SupportReportContext context,
  ) {
    final fields = <SupportReportPdfField>[];

    if (context == SupportReportContext.support) {
      fields.add(
        SupportReportPdfField(
          'رقم الطالب لدى الجهة',
          _optional(student.supportStudentNumber),
        ),
      );
    }

    fields.addAll(<SupportReportPdfField>[
      SupportReportPdfField('اسم الطالب', student.studentName),
      SupportReportPdfField(
        'الجزء الحالي',
        student.currentJuz?.toString() ?? 'غير مسجل',
      ),
      SupportReportPdfField('مقرر اليوم', _optional(student.dailyPlanText)),
    ]);

    if (context == SupportReportContext.support) {
      fields.add(
        SupportReportPdfField(
          'مقرر الشهر (وجه)',
          student.monthlyGoalQuarterFaces == null
              ? 'غير مسجل'
              : _facesText(student.monthlyGoalQuarterFaces!),
        ),
      );
    }

    final note = student.note?.trim();
    if (note != null && note.isNotEmpty) {
      fields.add(SupportReportPdfField('ملاحظة', note));
    }

    return fields;
  }

  List<SupportReportPdfField> _monthlyStudentFields(
    ApprovedMonthlySupportReportStudentSnapshot student,
    SupportReportContext context,
  ) {
    final fields = <SupportReportPdfField>[];

    if (context == SupportReportContext.support) {
      fields.add(
        SupportReportPdfField(
          'رقم الطالب لدى الجهة',
          _optional(student.supportStudentNumber),
        ),
      );
    }

    fields.addAll(<SupportReportPdfField>[
      SupportReportPdfField('اسم الطالب', student.studentName),
      SupportReportPdfField(
        'الجزء الحالي',
        student.currentJuz?.toString() ?? 'غير مسجل',
      ),
      SupportReportPdfField('مقرر اليوم', _optional(student.dailyPlanText)),
    ]);

    if (context == SupportReportContext.support) {
      fields.add(
        SupportReportPdfField(
          'مقرر الشهر (وجه)',
          student.monthlyGoalQuarterFaces == null
              ? 'غير مسجل'
              : _facesText(student.monthlyGoalQuarterFaces!),
        ),
      );
    }

    return fields;
  }

  List<SupportReportPdfField> _monthlyAggregates(
    ApprovedMonthlySupportReportStudentSnapshot student,
    SupportReportContext context,
  ) {
    final fields = <SupportReportPdfField>[
      SupportReportPdfField('أيام الغياب', student.absenceDays.toString()),
    ];

    if (context == SupportReportContext.support) {
      fields.add(
        SupportReportPdfField(
          'إتمام الهدف',
          student.goalCompleted == null
              ? 'غير مسجل'
              : student.goalCompleted!
              ? 'تم'
              : 'لم يتم',
        ),
      );
    }

    fields.add(
      SupportReportPdfField(
        'الإنجاز (وجه)',
        _facesText(student.achievedQuarterFaces),
      ),
    );

    fields.add(
      SupportReportPdfField('الملاحظات الشهرية', _optional(student.note)),
    );

    return fields;
  }

  String _weeklyDayLine(
    ApprovedWeeklySupportReportDaySnapshot day,
    int sourceStudentId,
  ) {
    final cells = _weeklyDayCells(day, sourceStudentId);
    return _dayLine(day.localDate, cells);
  }

  String _monthlyDayLine(
    ApprovedMonthlySupportReportDaySnapshot day,
    int sourceStudentId,
  ) {
    final cells = _monthlyDayCells(day, sourceStudentId);
    return _dayLine(day.localDate, cells);
  }

  String _dayLine(DateTime date, _SupportReportPdfDayCells cells) {
    return '${_weekdayArabic(date)} ${_dateText(date)}'
        ' | الحضور: ${cells.attendance}'
        ' | من/إلى: ${cells.rangeText}'
        ' | الإنجاز (وجه): ${cells.achievedFaces}'
        ' | الملاحظات: ${cells.noteText}';
  }

  _SupportReportPdfDayCells _weeklyDayCells(
    ApprovedWeeklySupportReportDaySnapshot day,
    int sourceStudentId,
  ) {
    if (day.dayKind != SupportReportDayKind.normal) {
      return _nonNormalDayCells(day.dayKind);
    }

    final entries =
        day.entries
            .where((entry) => entry.sourceStudentId == sourceStudentId)
            .toList()
          ..sort((left, right) => left.entryOrder.compareTo(right.entryOrder));

    SupportReportAttendanceStatus? attendanceStatus;
    var achievedQuarterFaces = 0;
    final ranges = <String>[];
    final notes = <String>[];

    for (final entry in entries) {
      attendanceStatus ??= entry.attendanceStatus;
      achievedQuarterFaces += entry.achievedQuarterFaces;

      if (entry.range != null) {
        ranges.add(_rangeText(entry.range!));
      }

      final note = entry.note?.trim();
      if (note != null && note.isNotEmpty) {
        notes.add(note);
      }
    }

    return _SupportReportPdfDayCells(
      attendance: attendanceStatus == null
          ? 'غير مسجل'
          : _attendanceText(attendanceStatus),
      rangeText: ranges.join('؛ '),
      achievedFaces: _facesText(achievedQuarterFaces),
      noteText: notes.join('؛ '),
    );
  }

  _SupportReportPdfDayCells _monthlyDayCells(
    ApprovedMonthlySupportReportDaySnapshot day,
    int sourceStudentId,
  ) {
    if (day.dayKind != SupportReportDayKind.normal) {
      return _nonNormalDayCells(day.dayKind);
    }

    final entries =
        day.entries
            .where((entry) => entry.sourceStudentId == sourceStudentId)
            .toList()
          ..sort((left, right) => left.entryOrder.compareTo(right.entryOrder));

    SupportReportAttendanceStatus? attendanceStatus;
    var achievedQuarterFaces = 0;
    final ranges = <String>[];
    final notes = <String>[];

    for (final entry in entries) {
      attendanceStatus ??= entry.attendanceStatus;
      achievedQuarterFaces += entry.achievedQuarterFaces;

      if (entry.range != null) {
        ranges.add(_rangeText(entry.range!));
      }

      final note = entry.note?.trim();
      if (note != null && note.isNotEmpty) {
        notes.add(note);
      }
    }

    return _SupportReportPdfDayCells(
      attendance: attendanceStatus == null
          ? 'غير مسجل'
          : _attendanceText(attendanceStatus),
      rangeText: ranges.join('؛ '),
      achievedFaces: _facesText(achievedQuarterFaces),
      noteText: notes.join('؛ '),
    );
  }

  _SupportReportPdfDayCells _nonNormalDayCells(SupportReportDayKind dayKind) {
    final attendance = switch (dayKind) {
      SupportReportDayKind.holiday => 'إجازة',
      SupportReportDayKind.missing => 'بيانات ناقصة',
      SupportReportDayKind.notApplicable => 'غير منطبق',
      SupportReportDayKind.normal => throw StateError(
        'Normal day must be resolved from its entries.',
      ),
    };

    return _SupportReportPdfDayCells(
      attendance: attendance,
      rangeText: '',
      achievedFaces: '0',
      noteText: '',
    );
  }

  String _rangeText(SupportReportQuranRange range) {
    final startName = QuranReferenceData.surahByNumber(
      range.startSurah,
    ).arabicName;
    final endName = QuranReferenceData.surahByNumber(range.endSurah).arabicName;

    if (range.startSurah == range.endSurah) {
      return '$startName ${range.startAyah}–${range.endAyah}';
    }

    return '$startName ${range.startAyah} → '
        '$endName ${range.endAyah}';
  }

  String _attendanceText(SupportReportAttendanceStatus status) {
    return switch (status) {
      SupportReportAttendanceStatus.present => 'حاضر',
      SupportReportAttendanceStatus.absent => 'غائب',
      SupportReportAttendanceStatus.excusedAbsent => 'غائب بعذر',
    };
  }

  String _weekdayArabic(DateTime date) {
    return switch (date.weekday) {
      DateTime.saturday => 'السبت',
      DateTime.sunday => 'الأحد',
      DateTime.monday => 'الاثنين',
      DateTime.tuesday => 'الثلاثاء',
      DateTime.wednesday => 'الأربعاء',
      DateTime.thursday => 'الخميس',
      DateTime.friday => 'الجمعة',
      _ => '',
    };
  }

  String _optional(String? value) {
    final normalized = value?.trim();
    return normalized == null || normalized.isEmpty ? 'غير مسجل' : normalized;
  }

  String _dateText(DateTime value) {
    final year = value.year.toString().padLeft(4, '0');
    final month = value.month.toString().padLeft(2, '0');
    final day = value.day.toString().padLeft(2, '0');
    return '$year-$month-$day';
  }

  String _facesText(int quarterFaces) {
    final value = quarterFaces / 4;
    return value == value.roundToDouble()
        ? value.toStringAsFixed(0)
        : value.toString();
  }
}

final class VerifiedSupportReportPdfGenerator {
  const VerifiedSupportReportPdfGenerator({
    this.mapper = const SupportReportPdfContentMapper(),
    this.verifier = const SupportReportPdfVerifier(),
    this.fontLoader = const AssetBundleSupportReportPdfFontLoader(),
  });

  final SupportReportPdfContentMapper mapper;
  final SupportReportPdfVerifier verifier;
  final SupportReportPdfFontLoader fontLoader;

  Future<VerifiedSupportReportPdf> generateWeekly(
    ApprovedWeeklySupportReportSnapshot snapshot,
  ) async {
    final model = mapper.buildWeekly(snapshot);
    final bytes = await _render(model);
    final verification = verifier.verifyStructure(bytes);

    if (!verification.isValid) {
      throw StateError(
        'Generated weekly PDF failed structural verification: '
        '${verification.reason}',
      );
    }

    return VerifiedSupportReportPdf(
      kind: SupportReportArtifactKind.weekly,
      fileName:
          'qurani_weekly_${_dateText(snapshot.period.weekStart)}_'
          '${_dateText(snapshot.period.weekEnd)}.pdf',
      sourceFingerprint: snapshot.sourceFingerprint,
      templateVersion: snapshot.header.templateVersion,
      sha256: await _sha256(bytes),
      bytes: bytes,
    );
  }

  Future<VerifiedSupportReportPdf> generateMonthly(
    ApprovedMonthlySupportReportSnapshot snapshot,
  ) async {
    final model = mapper.buildMonthly(snapshot);
    final bytes = await _render(model);
    final verification = verifier.verifyStructure(bytes);

    if (!verification.isValid) {
      throw StateError(
        'Generated monthly PDF failed structural verification: '
        '${verification.reason}',
      );
    }

    return VerifiedSupportReportPdf(
      kind: SupportReportArtifactKind.monthly,
      fileName:
          'qurani_monthly_'
          '${snapshot.period.year.toString().padLeft(4, '0')}-'
          '${snapshot.period.month.toString().padLeft(2, '0')}.pdf',
      sourceFingerprint: snapshot.sourceFingerprint,
      templateVersion: snapshot.header.templateVersion,
      sha256: await _sha256(bytes),
      bytes: bytes,
    );
  }

  Future<List<int>> _render(SupportReportPdfDocumentModel model) async {
    final fontBytes = await fontLoader.load();
    final regularFont = pw.Font.ttf(ByteData.sublistView(fontBytes.regular));
    final boldFont = pw.Font.ttf(ByteData.sublistView(fontBytes.bold));
    final document = pw.Document(
      title: model.title,
      creator: 'Qurani Package 8',
      theme: pw.ThemeData.withFont(base: regularFont, bold: boldFont),
    );

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        textDirection: pw.TextDirection.rtl,
        build: (context) {
          final widgets = <pw.Widget>[
            pw.Text(
              model.title,
              textDirection: pw.TextDirection.rtl,
              textAlign: pw.TextAlign.right,
              style: pw.TextStyle(
                font: boldFont,
                fontSize: 22,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 12),
          ];

          for (final field in model.metadata) {
            widgets.add(
              _fieldText(field, regularFont: regularFont, boldFont: boldFont),
            );
          }

          widgets.add(pw.SizedBox(height: 14));

          for (final student in model.students) {
            widgets.add(
              pw.Text(
                student.studentName,
                textDirection: pw.TextDirection.rtl,
                textAlign: pw.TextAlign.right,
                style: pw.TextStyle(
                  font: boldFont,
                  fontSize: 16,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
            );
            widgets.add(pw.SizedBox(height: 5));

            for (final field in student.fields) {
              widgets.add(
                _fieldText(field, regularFont: regularFont, boldFont: boldFont),
              );
            }

            for (final field in student.aggregates) {
              widgets.add(
                _fieldText(field, regularFont: regularFont, boldFont: boldFont),
              );
            }

            if (student.dayLines.isNotEmpty) {
              widgets.add(pw.SizedBox(height: 5));
              widgets.add(
                pw.Text(
                  'التفاصيل اليومية',
                  textDirection: pw.TextDirection.rtl,
                  textAlign: pw.TextAlign.right,
                  style: pw.TextStyle(
                    font: boldFont,
                    fontSize: 12,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
              );

              for (final line in student.dayLines) {
                widgets.add(
                  pw.Text(
                    line,
                    textDirection: pw.TextDirection.rtl,
                    textAlign: pw.TextAlign.right,
                    style: pw.TextStyle(font: regularFont, fontSize: 10),
                  ),
                );
              }
            }

            widgets.add(pw.SizedBox(height: 8));
            widgets.add(pw.Divider());
            widgets.add(pw.SizedBox(height: 8));
          }

          return widgets;
        },
      ),
    );

    final bytes = await document.save();
    return List<int>.unmodifiable(bytes);
  }

  pw.Widget _fieldText(
    SupportReportPdfField field, {
    required pw.Font regularFont,
    required pw.Font boldFont,
  }) {
    return pw.Text(
      '${field.label}: ${field.value}',
      textDirection: pw.TextDirection.rtl,
      textAlign: pw.TextAlign.right,
      style: pw.TextStyle(font: regularFont, fontSize: 11),
    );
  }

  Future<String> _sha256(List<int> bytes) async {
    final hash = await Sha256().hash(bytes);
    return hash.bytes
        .map((byte) => byte.toRadixString(16).padLeft(2, '0'))
        .join();
  }

  String _dateText(DateTime value) {
    final year = value.year.toString().padLeft(4, '0');
    final month = value.month.toString().padLeft(2, '0');
    final day = value.day.toString().padLeft(2, '0');
    return '$year-$month-$day';
  }
}

